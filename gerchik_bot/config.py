@dataclass
class TradingConfig:
    """
    Единая конфигурация всего бота.
    Изменяй здесь — изменения подхватятся во всех модулях.
    """

    # ── Таймфрейм ──────────────────────────────────────────────────────────
    # Рабочий таймфрейм свечей. По Герчику — 5 минут.
    entry_interval: str = Client.KLINE_INTERVAL_5MINUTE

    # ── Уровни поддержки / сопротивления ───────────────────────────────────
    # Сколько последних свечей использовать для нахождения уровней.
    # Больше свечей → более долгосрочные уровни.
    level_candles: int = 20

    # ── Фильтры ложного пробоя ─────────────────────────────────────────────
    # Объём пробойной свечи должен быть НИЖЕ этого % от среднего.
    # 0.7 = объём меньше 70% от среднего → пробой слабый → ложный.
    volume_threshold: float = 0.7

    # Тело свечи должно быть МЕНЬШЕ этой доли от всего диапазона high-low.
    # 0.3 = тело < 30% → длинный хвост → разворот.
    body_threshold: float = 0.3

    # ── Управление капиталом (правила Герчика) ─────────────────────────────
    # Доля депозита, которой рискуем в одной сделке.
    # 0.01 = 1% от баланса — стандартный риск Герчика.
    risk_per_trade: float = 0.01

    # Соотношение прибыль / риск.
    # 3.0 = правило 1:3 (тейк = стоп × 3).
    reward_ratio: float = 3.0

    # ── Кредитное плечо ────────────────────────────────────────────────────
    # Плечо на фьючерсах. При 5x позиция в 5 раз больше маржи.
    # ВНИМАНИЕ: плечо учитывается в расчёте размера позиции!
    leverage: int = 5

    # ── Лимиты позиций ─────────────────────────────────────────────────────
    # Максимум одновременно открытых позиций по всем инструментам.
    max_positions: int = 6

    # Одна позиция занимает не более этой доли от (баланс × плечо).
    # 0.20 = позиция не более 20% от размера счёта — защита от перегруза.
    max_position_size_pct: float = 0.20

    # ── Стоп-лосс ──────────────────────────────────────────────────────────
    # Буфер за экстремум пробойной свечи.
    # 0.002 = стоп ставится на 0.2% дальше минимума / максимума свечи.
    stop_buffer_pct: float = 0.002

    # Минимальный зазор между текущей ценой и уровнем SL/TP при выставлении.
    # Нужен чтобы ордер не сработал сразу после открытия позиции.
    min_trigger_gap_pct: float = 0.001

    # ── Трейлинг-стоп ──────────────────────────────────────────────────────
    # Включить / выключить трейлинг-стоп.
    trailing_stop_enabled: bool = True

    # На сколько процентов прибыль должна вырасти, чтобы трейлинг активировался.
    # 0.01 = активируется при прибыли 1% от цены входа.
    trailing_activation_pct: float = 0.01

    # Отступ трейлинг-стопа от лучшей достигнутой цены.
    # 0.015 = стоп тянется в 1.5% от максимума (для long) или минимума (для short).
    trailing_stop_pct: float = 0.015

    # ── Зеркальные уровни ──────────────────────────────────────────────────
    # Сколько свечей загружать для поиска зеркальных уровней.
    # level_lookback=100 + запас ~10 свечей на avg_volume rolling.
    mirror_candles: int = 110

    # ── Логирование ────────────────────────────────────────────────────────
    # Уровень логов: DEBUG / INFO / WARNING / ERROR
    log_level: str = "INFO"

    # Путь к файлу лога (None = только в консоль)
    log_file: str = "logs/bot.log"

    # ── Telegram-уведомления ───────────────────────────────────────────────
    telegram_enabled: bool = True


