@dataclass
class FalseBreakoutConfig:
    """Параметры стратегии «Ложный пробой»."""
    # Максимальная доля объёма от среднего для «слабого» пробоя
    volume_threshold: float = 0.7
    # Максимальная доля тела от диапазона свечи
    body_threshold: float = 0.3


@dataclass
class Base3CandlesConfig:
    """Параметры стратегии «База 3 свечи»."""
    # Максимальное расстояние от уровня, чтобы свеча считалась «касанием» (0.2%)
    touch_threshold: float = 0.002
    # Сколько свечей подряд должны касаться уровня
    candles_required: int = 3
    # Минимальный объём подтверждающей свечи (доля от среднего)
    volume_confirm_threshold: float = 0.8
    # Буфер стопа за уровень
    stop_buffer: float = 0.001
    # Соотношение риск/прибыль
    reward_ratio: float = 3.0
    # Период скользящей средней для фильтра тренда
    ma_period: int = 50


@dataclass
class BounceConfig:
    """Параметры стратегии «Отбой от уровня»."""
    # Максимальное расстояние цены от уровня для входа (0.3%)
    proximity_threshold: float = 0.003
    # Минимальный объём сигнальной свечи (в разах от среднего)
    volume_threshold: float = 1.5
    # Максимальная доля тела пин-бара от диапазона (30%)
    pin_bar_body_ratio: float = 0.3
    # Минимальная доля хвоста пин-бара от диапазона (60%)
    pin_bar_wick_ratio: float = 0.6
    # Максимальная доля тела доджи от диапазона (10%)
    doji_body_ratio: float = 0.1
    # Буфер стопа за уровень
    stop_buffer: float = 0.001
    # Соотношение риск/прибыль
    reward_ratio: float = 3.0


@dataclass
class MirrorLevelConfig:
    """Параметры стратегии «Зеркальный уровень»."""
    # Минимум касаний уровня до пробоя
    min_touches: int = 3
    # Минимум свечей между касаниями
    min_candles_at_level: int = 5
    # Порог близости к уровню (0.2%)
    touch_threshold: float = 0.002
    # Объём пробоя должен превышать средний в это число раз
    breakout_volume_mult: float = 1.2
    # Минимальная дистанция пробоя от уровня (0.5%)
    breakout_min_distance: float = 0.005
    # Порог близости к уровню при ретесте (0.3%)
    retest_threshold: float = 0.003
    # Минимум свечей после пробоя до ретеста
    min_candles_after_break: int = 3
    # Максимум свечей — если ретест не пришёл за это время, уровень сгорает
    max_candles_after_break: int = 50
    # Буфер стопа за уровень
    stop_buffer: float = 0.002
    # Соотношение риск/прибыль
    reward_ratio: float = 3.0
    # Глубина истории для поиска уровней (свечей)
    level_lookback: int = 100
    # Порог кластеризации уровней (близкие уровни объединяются)
    level_cluster_threshold: float = 0.003


